-- Khởi tạo các bảng phục vụ tài khoản và bootstrap Admin theo SRS V1.0.
-- Chạy bằng psql kết nối database quản trị (ví dụ postgres); cần quyền tạo database/extension.
-- Mật khẩu admin123 là mật khẩu tạm công khai, chỉ dùng trong quy trình setup
-- được bảo vệ. Backend phải xác minh mật khẩu bằng pgcrypto crypt() tương thích.

\set ON_ERROR_STOP on

SELECT 'CREATE DATABASE quan_ly_so_doan'
WHERE NOT EXISTS (
    SELECT 1 FROM pg_database WHERE datname = 'quan_ly_so_doan'
)\gexec

\connect quan_ly_so_doan

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS classes (
    class_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_code VARCHAR(50) NOT NULL UNIQUE,
    class_name VARCHAR(150) NOT NULL
);

CREATE TABLE IF NOT EXISTS students (
    mssv VARCHAR(20) PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    class_id BIGINT NOT NULL REFERENCES classes(class_id),
    date_of_birth DATE,
    gender VARCHAR(20),
    phone_number VARCHAR(20),
    email VARCHAR(254),
    hometown VARCHAR(255),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS students_class_id_idx
    ON students (class_id);

CREATE SEQUENCE IF NOT EXISTS staff_profiles_code_seq;

CREATE TABLE IF NOT EXISTS staff_profiles (
    staff_code VARCHAR(20) PRIMARY KEY
        DEFAULT lpad(nextval('staff_profiles_code_seq')::text, 6, '0'),
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(254),
    phone_number VARCHAR(20),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT staff_profiles_name_not_blank CHECK (btrim(full_name) <> ''),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER SEQUENCE staff_profiles_code_seq
    OWNED BY staff_profiles.staff_code;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'staff_profiles'
          AND column_name IN ('unit', 'title')
    ) THEN
        IF EXISTS (
            SELECT 1 FROM staff_profiles
            WHERE unit IS NOT NULL OR title IS NOT NULL
        ) THEN
            RAISE EXCEPTION
                'staff_profiles has unit/title data; export or clear it before applying this schema update';
        END IF;
        ALTER TABLE staff_profiles
            DROP COLUMN IF EXISTS unit,
            DROP COLUMN IF EXISTS title;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS accounts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username VARCHAR(100) NOT NULL,
    password_hash TEXT NOT NULL,
    person_type VARCHAR(10) NOT NULL
        CHECK (person_type IN ('STUDENT', 'STAFF', 'SYSTEM')),
    person_code VARCHAR(50),
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('ADMIN', 'SECRETARY', 'OFFICER')),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('SETUP_REQUIRED', 'ACTIVE', 'DISABLED')),
    recovery_email VARCHAR(254),
    recovery_email_verified_at TIMESTAMPTZ,
    setup_completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT accounts_username_normalized
        CHECK (username = lower(btrim(username))),
    CONSTRAINT accounts_person_identity
        CHECK (
            (person_type = 'SYSTEM' AND person_code IS NULL AND role = 'ADMIN')
            OR (person_type IN ('STUDENT', 'STAFF') AND person_code IS NOT NULL)
        ),
    CONSTRAINT accounts_setup_status
        CHECK (status <> 'SETUP_REQUIRED' OR person_type = 'SYSTEM')
);

CREATE UNIQUE INDEX IF NOT EXISTS accounts_username_uq
    ON accounts (lower(username));

CREATE UNIQUE INDEX IF NOT EXISTS accounts_single_system_uq
    ON accounts (person_type)
    WHERE person_type = 'SYSTEM';

CREATE UNIQUE INDEX IF NOT EXISTS accounts_single_active_secretary_uq
    ON accounts (role)
    WHERE role = 'SECRETARY' AND status = 'ACTIVE';

CREATE TABLE IF NOT EXISTS system_state (
    singleton SMALLINT PRIMARY KEY DEFAULT 1 CHECK (singleton = 1),
    initialized_at TIMESTAMPTZ,
    initial_admin_id UUID REFERENCES accounts(id) ON DELETE SET NULL,
    setup_version INTEGER NOT NULL DEFAULT 1 CHECK (setup_version > 0),
    bootstrap_token_hash TEXT
);

ALTER TABLE system_state
    ADD COLUMN IF NOT EXISTS bootstrap_token_hash TEXT;

CREATE TABLE IF NOT EXISTS mail_settings (
    singleton SMALLINT PRIMARY KEY DEFAULT 1 CHECK (singleton = 1),
    recovery_email VARCHAR(254) NOT NULL,
    smtp_host VARCHAR(255) NOT NULL,
    smtp_port INTEGER NOT NULL CHECK (smtp_port BETWEEN 1 AND 65535),
    smtp_username VARCHAR(254) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE mail_settings
    DROP COLUMN IF EXISTS smtp_app_password;

CREATE TABLE IF NOT EXISTS otp_verifications (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    account_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    purpose VARCHAR(20) NOT NULL
        CHECK (purpose IN ('SETUP_EMAIL', 'RESET_PASSWORD')),
    otp_hash TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    attempts SMALLINT NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 5),
    consumed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS otp_verifications_account_purpose_idx
    ON otp_verifications (account_id, purpose, created_at DESC);

CREATE TABLE IF NOT EXISTS security_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_account_id UUID NOT NULL REFERENCES accounts(id),
    action VARCHAR(50) NOT NULL,
    target_type VARCHAR(50) NOT NULL,
    target_id VARCHAR(100) NOT NULL,
    old_values JSONB,
    new_values JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS security_audit_logs_actor_created_idx
    ON security_audit_logs (actor_account_id, created_at DESC);

CREATE INDEX IF NOT EXISTS security_audit_logs_target_idx
    ON security_audit_logs (target_type, target_id, created_at DESC);

-- Seed chỉ khi system_state chưa ghi nhận khởi tạo hoàn tất.
-- Nếu Admin bị xóa sau khi initialized_at được đặt, chạy lại init.sql sẽ không
-- tái tạo admin/admin123 (theo AT-23 của SRS).
INSERT INTO accounts (
    username,
    password_hash,
    person_type,
    person_code,
    role,
    status
)
SELECT
    'admin',
    crypt('admin123', gen_salt('bf', 12)),
    'SYSTEM',
    NULL,
    'ADMIN',
    'SETUP_REQUIRED'
WHERE NOT EXISTS (
    SELECT 1
    FROM system_state
    WHERE singleton = 1 AND initialized_at IS NOT NULL
)
ON CONFLICT DO NOTHING;

INSERT INTO system_state (singleton, initial_admin_id, setup_version)
SELECT 1, id, 1
FROM accounts
WHERE username = 'admin' AND person_type = 'SYSTEM'
ON CONFLICT (singleton) DO NOTHING;

COMMIT;
